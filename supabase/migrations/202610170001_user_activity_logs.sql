create table if not exists public.mw_user_activity_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  username text not null,
  department text not null default '',
  session_id uuid not null,
  action text not null,
  details text not null default '',
  succeeded boolean not null default true,
  occurred_at timestamptz not null default now()
);

create index if not exists mw_user_activity_logs_user_time_idx
  on public.mw_user_activity_logs (user_id, occurred_at desc, id desc);

create index if not exists mw_user_activity_logs_session_time_idx
  on public.mw_user_activity_logs (session_id, occurred_at asc, id asc);

alter table public.mw_user_activity_logs enable row level security;
revoke all on public.mw_user_activity_logs from public, anon, authenticated;
grant all on public.mw_user_activity_logs to service_role;
